import java.util.ArrayList;

public class Theatre {

    public static void main(String[] args) {
        Actor firstActor = new Actor("Джонни", "Депп", Gender.MALE, 178);
        Actor secondActor = new Actor("Олег", "Меньшиков", Gender.MALE, 174);
        Actor thirdActor = new Actor("Джессика", "Альба", Gender.FEMALE, 169);

        Director firstDirector = new Director("Никита", "Михалков", Gender.MALE, 5);
        Director secondDirector = new Director("Хлоя", "Чжао", Gender.FEMALE, 3);

        Person musicAuthor = new Person("Петр", "Чайковский", Gender.MALE);
        Person choreographer = new Person("Николай", "Цискаридзе", Gender.MALE);

        Show drama = new Show("Два берега одной Победы", 150, firstDirector, new ArrayList<>());

        String operaLibretto = """
                Действующие лица:
                Кармен — свободолюбивая цыганка.
                Хосе — солдат, влюбленный в Кармен.
                Микаэла — девушка из родной деревни Хосе.
                Эскамильо — прославленный тореадор.
                
                Действие I.
                Площадь в Севилье. Солдаты охраняют сигарную фабрику.
                Кармен дразнит мужчин, поет о том, что любовь — птица, которой нельзя приказывать.
                В драке на фабрике винят Кармен, ее арестовывают и поручают Хосе.
                Кармен играет с его чувствами, обещает любовь и уговаривает отпустить ее.
                Хосе поддается, Кармен сбегает, а Хосе попадает под арест.
                
                Действие II.
                Таверна. Цыгане и контрабандисты веселятся.
                Кармен танцует, появляется Эскамильо и добивается ее внимания.
                Выходит Хосе после ареста, признается Кармен в чувствах.
                Кармен требует доказать любовь: бросить службу и уйти с ней к контрабандистам.
                Хосе колеблется, но в итоге нарушает приказ и следует за ней.
                
                Действие III.
                Горы, укрытие контрабандистов.
                Хосе не привык к разбойничьей жизни, его мучают ревность и сомнения.
                Микаэла находит лагерь, умоляет Хосе вернуться к умирающей матери.
                Кармен чувствует, что их страсть угасла, и все чаще смотрит в сторону Эскамильо.
                Хосе уходит к матери, но обещает вернуться.
                
                Действие IV.
                Площадь перед ареной для корриды.
                Толпа встречает Эскамильо, Кармен гордо идет с ним.
                Хосе отчаянно пытается вернуть Кармен, умоляет не бросать его.
                Кармен остается верна своей свободе и говорит, что между ними все кончено.
                В вспышке отчаяния Хосе закалывает Кармен ножом, когда внутри арены звучат крики толпы.
                """;
        Opera opera = new Opera(
                "Кармен",
                170,
                secondDirector,
                new ArrayList<>(),
                musicAuthor,
                operaLibretto,
                36
        );

        String balletLibretto = """
                Действующие лица:
                Зигфрид — принц.
                Одетта — заколдованная принцесса-лебедь.
                Одиллия — двойник Одетты (черный лебедь).
                Ротбарт — злой чародей.
                
                Действие I.
                Дворцовый сад. Праздник совершеннолетия принца Зигфрида.
                Все танцуют, мать напоминает, что на завтрашнем балу он должен выбрать невесту.
                Зигфрид тоскует по настоящей любви и свободе.
                С наступлением вечера он отправляется на охоту с арбалетом.
                
                Действие II.
                Ночное озеро. Появляется стая лебедей.
                Зигфрид хочет выстрелить, но один лебедь превращается в девушку — это Одетта.
                Она рассказывает, что девушки заколдованы Ротбартом и днем становятся лебедями.
                Разрушить чары может лишь верная любовь, клятва которой не будет нарушена.
                Зигфрид клянется Одетте в вечной любви, но рассвет разлучает их.
                
                Действие III.
                Дворцовый бал. Принцу приводят знатных невест.
                Неожиданно появляется Ротбарт с Одиллией, удивительно похожей на Одетту, но в черном.
                Одиллия очаровывает принца, они танцуют блистательное па-де-де.
                Зигфрид перед всем двором клянется ей в любви, думая, что это Одетта.
                В тот же миг видение настоящей Одетты у озера разоблачает обман.
                Потрясенный Зигфрид спешит обратно к озеру.
                
                Действие IV.
                У озера. Одетта в отчаянии, чары Ротбарта почти необратимы.
                Зигфрид просит прощения, но клятва уже нарушена.
                В разных версиях финала герои либо гибнут и воссоединяются в ином мире,
                либо побеждают Ротбарта и снимают заклятие.
                Во всяком случае, любовь Зигфрида и Одетты сильнее страха и колдовства.
                """;
        Ballet ballet = new Ballet(
                "Лебединое озеро",
                150,
                firstDirector,
                new ArrayList<>(),
                musicAuthor,
                balletLibretto,
                choreographer
        );

        drama.addActor(firstActor);
        drama.addActor(secondActor);

        opera.addActor(secondActor);
        opera.addActor(thirdActor);
        opera.addActor(secondActor);

        ballet.addActor(firstActor);
        ballet.addActor(thirdActor);

        drama.printDirectorInfo();
        drama.printActors();
        printSeparatingLine();

        opera.printDirectorInfo();
        opera.printActors();
        printSeparatingLine();

        ballet.printDirectorInfo();
        ballet.printActors();
        printSeparatingLine();

        drama.replaceActor(firstActor, thirdActor);
        drama.printActors();
        printSeparatingLine();

        opera.replaceActor(firstActor, firstActor);
        printSeparatingLine();

        opera.printLibretto();
        printSeparatingLine();

        ballet.printLibretto();
    }

    public static void printSeparatingLine() {
        System.out.println("=".repeat(20));
    }
}
